const fallbackTransliterate = (word: string) => {
  if (word.length <= 2 && word.toUpperCase() === word) {
    return word;
  }

  return word
    .toLowerCase()
    .split('')
    .map(char => fallbackLetters[char] || char)
    .join('');
};

export const toReadableHindi = (text?: string | null) => {
  const rawText = String(text || '');
  const trimmedText = rawText.trim();
  if (!trimmedText) {
    return rawText;
  }

  const exact = exactHinglish[trimmedText];
  if (exact) {
    return rawText.replace(trimmedText, exact);
  }

  let output = rawText;
  phraseReplacements.forEach(([pattern, replacement]) => {
    output = output.replace(pattern, replacement);
  });

  output = output.replace(/[A-Za-z]+/g, word => (
    wordHinglish[word.toLowerCase()] || fallbackTransliterate(word)
  ));

  return output;
};
